from typing import List, Dict, Optional, Type
from datetime import datetime

from src.data.models import Bar, TimeFrame
from src.storage.repository import MarketDataRepository
from src.strategy.base import Strategy, Signal, SignalAction


class StrategyEngine:
    """Multi-strategy orchestration engine.

    Coordinates running multiple registered strategies over historical
    and real-time bars, with consensus ranking and signal deduplication.
    """

    def __init__(self, repo: Optional[MarketDataRepository] = None):
        self.repo = repo
        self._strategies: Dict[str, Strategy] = {}

    def register_strategy(self, strategy: Strategy) -> None:
        """Register a strategy with the engine.

        Args:
            strategy: Strategy instance to register
        """
        self._strategies[strategy.name] = strategy

    def unregister_strategy(self, name: str) -> bool:
        """Unregister a strategy by name.

        Args:
            name: Strategy name to remove

        Returns:
            True if strategy was found and removed, False otherwise
        """
        if name in self._strategies:
            del self._strategies[name]
            return True
        return False

    def list_strategies(self) -> List[str]:
        """List all registered strategy names.

        Returns:
            List of strategy names
        """
        return list(self._strategies.keys())

    def get_strategy(self, name: str) -> Optional[Strategy]:
        """Get a strategy by name.

        Args:
            name: Strategy name

        Returns:
            Strategy instance or None if not found
        """
        return self._strategies.get(name)

    def run_strategy(self, strategy_name: str, bars: List[Bar]) -> List[Signal]:
        """Run a single strategy on the provided bars.

        Args:
            strategy_name: Name of strategy to run
            bars: Chronologically sorted bars

        Returns:
            List of signals generated by the strategy
        """
        strategy = self._strategies.get(strategy_name)
        if strategy is None:
            return []
        return strategy.generate_signals(bars)

    def run_all(self, bars: List[Bar]) -> Dict[str, List[Signal]]:
        """Run all registered strategies on the provided bars.

        Args:
            bars: Chronologically sorted bars

        Returns:
            Dictionary mapping strategy names to their generated signals
        """
        results: Dict[str, List[Signal]] = {}
        for name, strategy in self._strategies.items():
            results[name] = strategy.generate_signals(bars)
        return results

    def evaluate_symbol(
        self,
        symbol: str,
        timeframe: TimeFrame,
        limit: int = 100,
    ) -> Dict[str, List[Signal]]:
        """Fetch bars from repository and run all strategies.

        Args:
            symbol: Ticker symbol
            timeframe: Bar timeframe
            limit: Number of bars to fetch

        Returns:
            Dictionary mapping strategy names to their generated signals
        """
        if self.repo is None:
            raise ValueError("No repository configured in StrategyEngine")

        bars = self.repo.get_bars(symbol, timeframe, limit=limit)
        if not bars:
            return {}

        # Sort by timestamp (oldest first) if not already sorted
        bars = sorted(bars, key=lambda b: b.timestamp)

        return self.run_all(bars)

    def get_consensus_signals(self, bars: List[Bar]) -> List[Signal]:
        """Get consensus signals when multiple strategies agree.

        Args:
            bars: Chronologically sorted bars

        Returns:
            List of consensus signals with aggregated confidence
        """
        all_signals = self.run_all(bars)

        # Group signals by timestamp and action
        signal_groups: Dict[str, List[Signal]] = {}

        for strategy_name, signals in all_signals.items():
            for sig in signals:
                key = f"{sig.symbol}:{sig.action.value}:{sig.timestamp.isoformat()}"
                if key not in signal_groups:
                    signal_groups[key] = []
                signal_groups[key].append(sig)

        # Filter to only groups with 2+ strategies agreeing
        consensus: List[Signal] = []
        for key, group in signal_groups.items():
            if len(group) >= 2:
                # Average confidence across agreeing strategies
                avg_confidence = sum(s.confidence for s in group) / len(group)
                # Use the most recent signal as template
                template = max(group, key=lambda s: s.timestamp)

                consensus.append(
                    Signal(
                        symbol=template.symbol,
                        action=template.action,
                        timestamp=template.timestamp,
                        price=template.price,
                        confidence=round(avg_confidence, 3),
                        strategy_name=f"CONSENSUS:{','.join(s.strategy_name for s in group)}",
                        indicators=template.indicators,
                        reason=f"Consensus ({len(group)} strategies): {template.reason}",
                        stop_loss=template.stop_loss,
                        take_profit=template.take_profit,
                    )
                )

        return consensus

    def get_latest_signals(self, bars: List[Bar]) -> Dict[str, Optional[Signal]]:
        """Get the most recent signal from each strategy.

        Args:
            bars: Chronologically sorted bars

        Returns:
            Dictionary mapping strategy names to their latest signal (or None)
        """
        results: Dict[str, Optional[Signal]] = {}
        for name, strategy in self._strategies.items():
            signals = strategy.generate_signals(bars)
            results[name] = signals[-1] if signals else None
        return results